  function fill(s, v) { return v ? String(s).replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(v, k) ? v[k] : m)) : s; }
  function t(s, v) { return fill(lang === 'id' && Object.prototype.hasOwnProperty.call(ID, s) ? ID[s] : s, v); }
  function setLang(l) {
    if (!LANGS[l]) return;
    try { g.localStorage.setItem(KEY, l); } catch (e) { /* ignore */ }
    g.location.reload();
  }

  // ---- formatting
  const isId = lang === 'id';
  const THOU = isId ? '.' : ',', DEC = isId ? ',' : '.';
  const MONTHS = isId ? ['Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun', 'Jul', 'Agu', 'Sep', 'Okt', 'Nov', 'Des'] : ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  function group(str) {
    const [i, d] = str.split('.');
    const neg = i.startsWith('-');
    const body = (neg ? i.slice(1) : i).replace(/\B(?=(\d{3})+(?!\d))/g, THOU);
    return (neg ? '−' : '') + body + (d !== undefined ? DEC + d : '');
  }
  const r = (x, dp) => (g.C ? g.C.round(x, dp) : Number(x));
  /** Money: no decimals when whole (Rupiah style), otherwise 2. */
  function fmtAmt(x) {
    const v = r(x, 2);
    return group(Number.isInteger(v) ? String(v) : v.toFixed(2));
  }
  /** Quantity: up to 4 decimals, trailing zeros removed. */
  function fmtQty(x) {
    let s = r(x, 4).toFixed(4).replace(/\.?0+$/, '');
    if (s === '-0') s = '0';
    return group(s);
  }
  function fmtPct(x) { return isFinite(x) ? r(x, 1).toFixed(1).replace('.', DEC) + '%' : '—'; }
  function fmtDate(iso) {
    if (!iso) return '—';
    const [y, m, d] = String(iso).slice(0, 10).split('-');
    return `${d}-${MONTHS[Number(m) - 1]}-${y}`;
  }

  /** Short date without the year (16 Nov) and month with year (Nov 2026), for chart axes. */
  function fmtShort(iso) { const [, m, d] = String(iso).split('-'); return `${Number(d)} ${MONTHS[Number(m) - 1]}`; }
  function fmtMonth(iso) { const [y, m] = String(iso).split('-'); return `${MONTHS[Number(m) - 1]} ${y}`; }
  /** Compact amounts for charts: 1,81 jt / 399 rb (Indonesian), 1.81M / 399K (English). Under 10,000 the number is
      written in full. Pass a unit from compactUnit(max) to keep one unit along an axis. */
  const UNITS = isId ? [[1e12, ' T'], [1e9, ' M'], [1e6, ' jt'], [1e3, ' rb']] : [[1e12, 'T'], [1e9, 'B'], [1e6, 'M'], [1e3, 'K']];
  function compactUnit(max) { return (Math.abs(max) >= 10000 && UNITS.find(([v]) => Math.abs(max) >= v)) || [1, '']; }
  function fmtCompact(x, unit) {
    const [div, suffix] = unit || compactUnit(x);
    const v = x / div, a = Math.abs(v);
    const dp = unit || a < 10 ? 2 : a < 100 ? 1 : 0;
    let s = r(v, dp).toFixed(dp);
    if (dp) s = s.replace(/\.?0+$/, '');
    if (s === '-0') s = '0';
    return group(s) + (s === '0' ? '' : suffix);
  }

